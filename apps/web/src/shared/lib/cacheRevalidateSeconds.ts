/**
 * Время жизни Data Cache для серверных префетчей (товары, категории).
 *
 * В разработке — ноль. Data Cache работает и в `next dev`: без этого условия
 * коллега, поправивший данные сидом или через psql, пять минут смотрел бы на
 * старую выдачу и искал баг не там. В остальных режимах — 300 секунд: каталог
 * правят штучно через админку, а её мутации сбрасывают кеш тегом сразу же
 * (см. features/catalog-admin/api/revalidate.ts), так что число влияет
 * только на правки в обход админки.
 *
 * Один источник на оба кеша (товары и категории): если бы каждый префетч
 * считал своё значение, они могли бы разойтись — например, кто-то поменяет
 * 300 на 600 в одном месте и забудет про второе.
 */
export const CACHE_REVALIDATE_SECONDS = process.env.NODE_ENV === 'development' ? 0 : 300;
