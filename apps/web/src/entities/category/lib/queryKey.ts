export const CATEGORY_LIST_QUERY_KEY = ['category-list'] as const;

/**
 * Общий gcTime для prefetchCategories и useCategories. Префетч кладёт запись
 * без наблюдателя — HeaderCatalog монтируется только по клику на «Каталог», —
 * а без активного наблюдателя запись живёт в кэше по тому gcTime, с которым её
 * туда положили. Если значения разойдутся, запись может быть вычищена раньше,
 * чем хук её прочитает, и первое открытие меню даст холодный запрос вместо
 * того, ради которого был написан префетч.
 */
export const CATEGORY_LIST_GC_TIME = 10 * 60 * 1000;
